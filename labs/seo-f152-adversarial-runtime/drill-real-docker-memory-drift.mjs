/**
 * SEO F152 — adversarial real Docker resource-limit drift drill.
 * Disposable GitHub Actions ONLY: tears down the CI-owned good container,
 * boots the same synthetic fixture with a wrong memory limit, proves F151
 * blocks it, then cleans it up. Never target a VPS, real service or client.
 */
import {writeFile,rm} from 'node:fs/promises';
import {join} from 'node:path';
import {execFileSync} from 'node:child_process';
import {makeCiOnlyMemoryDriftFixture} from './memory-drift-ci-only.mjs';
import {reviewRunningStagingContainer} from
  '../seo-f151-docker-runtime/audit-running-container.mjs';

const cmd=(args,options={})=>execFileSync('docker',args,{
  timeout:120000,stdio:'ignore',...options
});
function getOnlyContainer(path){
 const id=cmd(['compose','-f',path,'ps','-q','nginx'],{
  encoding:'utf8',timeout:15000,maxBuffer:256*1024,
  stdio:['ignore','pipe','ignore']
 }).trim();
 if(!/^[0-9a-f]{12,64}$/.test(id))
   throw Error('SEO F152: expected only one temporary Nginx');
 const raw=cmd(['inspect',id],{
  encoding:'utf8',timeout:15000,maxBuffer:2*1024*1024,
  stdio:['ignore','pipe','ignore']
 });
 const records=JSON.parse(raw);
 if(!Array.isArray(records)||records.length!==1)
   throw Error('SEO F152: invalid local inspect');
 return records[0];
}
export async function runCiOnlyMemoryDriftDrill(input){
 if(process.env.CI!=='true'||process.env.GITHUB_ACTIONS!=='true'||
    process.env.APP_ENV!=='testing'||
    process.env.SEO_F138_LOOPBACK_STAGING!=='YES_I_CONTROL_THIS_LOOPBACK'||
    !input||typeof input!=='object'||Array.isArray(input)||
    !['baselineYaml','baselineCompose','temporaryDirectory',
      'expectedRuntime'].every(k=>Object.hasOwn(input,k))||
    Object.keys(input).length!==4||
    input.expectedRuntime?.memoryLimitMiB!==512)
   throw Error('SEO F152: runner-only approved synthetic baseline required');
 // The baseline is precisely the YAML generated by F149.
 const badCompose=makeCiOnlyMemoryDriftFixture(input.baselineCompose);
 const negativeYaml=join(input.temporaryDirectory,'f152-negative-memory.yml');
 let negativeStarted=false;
 // Good Nginx and valid HTTP/HTML F143 must have passed before calling.
 cmd(['compose','-f',input.baselineYaml,'down','--volumes','--remove-orphans']);
 try{
   await writeFile(negativeYaml,badCompose,{flag:'wx',mode:0o600});
   cmd(['compose','-f',negativeYaml,'config','--quiet']);
   negativeStarted=true;
   cmd(['compose','-f',negativeYaml,'up','-d','--wait',
        '--pull','never','--no-build']);
   const audited=reviewRunningStagingContainer({
     inspect:getOnlyContainer(negativeYaml),
     expected:input.expectedRuntime
   });
   if(audited.reviewStatus!=='blocked'||
      !audited.blockedComponents.includes('cpu_memory_or_pid_limit_drift')||
      audited.summary.requestedResourcesEnforced||
      audited.productionDeploymentAuthorized)
     throw Error('SEO F152: real Docker memory drift was not denied');
   return {
     contractVersion:'seo-f152-adversarial-docker-memory-drift-ci-v1',
     reviewStatus:'expected_runtime_drift_blocked_in_lab',
     detectedRule:'cpu_memory_or_pid_limit_drift',
     privateFixtureOnly:true,
     actualDockerContainerInspected:true,
     productionReleaseAuthorized:false,
     leasewebHostVerified:false
   };
 }finally{
   if(negativeStarted){
     try{cmd(['compose','-f',negativeYaml,'down','--volumes',
       '--remove-orphans']);}
     catch{/* disposable CI teardown; GitHub runner will be discarded */}
   }
   await rm(negativeYaml,{force:true});
 }
}
